create table acordo_honorarios (
    id                  bigint generated by default as identity primary key,
    atendimento_id      bigint         not null references atendimento (id),
    forma_cobranca      varchar(20)    not null,
    valor_contratado    numeric(15, 2),
    percentual          numeric(5, 2),
    base_calculo        varchar(500),
    quantidade_parcelas integer,
    condicoes           varchar(2000),
    data_acordo         date           not null,
    criado_em           timestamp      not null,
    atualizado_em       timestamp      not null,
    constraint uk_acordo_atendimento unique (atendimento_id),
    constraint ck_acordo_forma check (forma_cobranca in ('VALOR_FIXO', 'PERCENTUAL', 'OUTRA')),
    constraint ck_acordo_valor check (valor_contratado is null or valor_contratado >= 0),
    constraint ck_acordo_percentual_faixa check (percentual is null or (percentual > 0 and percentual <= 100)),
    constraint ck_acordo_parcelas check (quantidade_parcelas is null or quantidade_parcelas > 0),
    constraint ck_acordo_valor_fixo check (forma_cobranca <> 'VALOR_FIXO' or valor_contratado is not null),
    constraint ck_acordo_percentual
        check ((forma_cobranca = 'PERCENTUAL') = (percentual is not null and base_calculo is not null))
);

create table parcela_honorario (
    id                  bigint generated by default as identity primary key,
    acordo_id           bigint         not null references acordo_honorarios (id),
    numero              integer        not null,
    vencimento          date           not null,
    valor               numeric(15, 2) not null,
    situacao            varchar(20)    not null,
    motivo_cancelamento varchar(500),
    cancelada_em        timestamp,
    cancelada_por       varchar(100),
    criado_em           timestamp      not null,
    atualizado_em       timestamp      not null,
    constraint ck_parcela_valor check (valor > 0),
    constraint ck_parcela_situacao check (situacao in ('ABERTA', 'PAGA', 'CANCELADA')),
    constraint ck_parcela_cancelamento
        check (situacao <> 'CANCELADA' or (motivo_cancelamento is not null and cancelada_em is not null))
);

create index ix_parcela_acordo on parcela_honorario (acordo_id);
create index ix_parcela_vencimento on parcela_honorario (vencimento);

create table recebimento_honorario (
    id                  bigint generated by default as identity primary key,
    acordo_id           bigint         not null references acordo_honorarios (id),
    parcela_id          bigint references parcela_honorario (id),
    data_recebimento    date           not null,
    valor               numeric(15, 2) not null,
    forma_pagamento     varchar(20)    not null,
    observacoes         varchar(2000),
    cancelado           boolean        not null default false,
    motivo_cancelamento varchar(500),
    cancelado_em        timestamp,
    cancelado_por       varchar(100),
    criado_em           timestamp      not null,
    atualizado_em       timestamp      not null,
    constraint ck_recebimento_valor check (valor > 0),
    constraint ck_recebimento_forma
        check (forma_pagamento in ('DINHEIRO', 'PIX', 'TRANSFERENCIA', 'BOLETO', 'OUTRO')),
    constraint ck_recebimento_cancelamento
        check (not cancelado or (motivo_cancelamento is not null and cancelado_em is not null))
);

create index ix_recebimento_acordo on recebimento_honorario (acordo_id);
create index ix_recebimento_parcela on recebimento_honorario (parcela_id);
create index ix_recebimento_data on recebimento_honorario (data_recebimento);
