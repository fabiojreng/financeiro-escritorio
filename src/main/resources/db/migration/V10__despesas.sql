create table despesa (
    id                  bigint generated by default as identity primary key,
    data_pagamento      date           not null,
    categoria_id        bigint         not null references categoria_despesa (id),
    forma_pagamento_id  bigint         not null references forma_pagamento_despesa (id),
    historico           varchar(200)   not null,
    numero_documento    varchar(100),
    valor               numeric(15, 2) not null,
    fornecedor          varchar(200)   not null,
    observacoes         varchar(2000),
    situacao            varchar(20)    not null,
    motivo_cancelamento varchar(500),
    cancelado_em        timestamp,
    cancelado_por       varchar(100),
    criado_em           timestamp      not null,
    atualizado_em       timestamp      not null,
    constraint ck_despesa_valor check (valor > 0),
    constraint ck_despesa_situacao check (situacao in ('ATIVA', 'CANCELADA')),
    constraint ck_despesa_cancelamento
        check (situacao <> 'CANCELADA' or (motivo_cancelamento is not null and cancelado_em is not null))
);

create index ix_despesa_data_pagamento on despesa (data_pagamento);
create index ix_despesa_categoria on despesa (categoria_id);
create index ix_despesa_forma_pagamento on despesa (forma_pagamento_id);

-- Um registro por mês (competência = primeiro dia do mês) enviado à contabilidade.
create table fechamento_despesa (
    id                bigint generated by default as identity primary key,
    competencia       date           not null,
    enviado           boolean        not null,
    enviado_em        timestamp,
    enviado_por       varchar(100),
    quantidade        integer,
    total             numeric(15, 2),
    reaberto_em       timestamp,
    reaberto_por      varchar(100),
    motivo_reabertura varchar(500),
    criado_em         timestamp      not null,
    atualizado_em     timestamp      not null,
    constraint uk_fechamento_despesa_competencia unique (competencia),
    constraint ck_fechamento_despesa_competencia check (extract(day from competencia) = 1),
    constraint ck_fechamento_despesa_envio
        check (not enviado or (enviado_em is not null and enviado_por is not null
                               and quantidade is not null and total is not null)),
    constraint ck_fechamento_despesa_reabertura
        check ((reaberto_em is null) = (motivo_reabertura is null))
);
