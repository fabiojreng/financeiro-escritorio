-- Controle mensal dos benefícios já concedidos aos clientes, separado da agenda de pagamentos.

create table beneficio_concedido (
    id              bigint generated by default as identity primary key,
    cliente_id      bigint    not null references cliente (id),
    tipo_servico_id bigint    not null references tipo_servico (id),
    responsavel_id  bigint    not null references responsavel (id),
    competencia     date      not null,
    criado_em       timestamp not null,
    atualizado_em   timestamp not null,
    constraint ck_beneficio_concedido_competencia check (extract(day from competencia) = 1)
);

create index ix_beneficio_concedido_competencia on beneficio_concedido (competencia);
create index ix_beneficio_concedido_cliente on beneficio_concedido (cliente_id);

-- Rotina do escritório: Administrador e Operador recebem o módulo inteiro.
insert into perfil_permissao (perfil_id, permissao)
select p.id, x.permissao
from perfil p
cross join (values ('BENEFICIOS_CONCEDIDOS_VISUALIZAR'), ('BENEFICIOS_CONCEDIDOS_EDITAR'),
                   ('BENEFICIOS_CONCEDIDOS_EXCLUIR')) as x (permissao)
where p.nome in ('Administrador', 'Operador');
