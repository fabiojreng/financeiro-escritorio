create table atendimento (
    id              bigint generated by default as identity primary key,
    cliente_id      bigint        not null references cliente (id),
    tipo_servico_id bigint        not null references tipo_servico (id),
    responsavel_id  bigint        not null references responsavel (id),
    numero_processo varchar(50),
    data_abertura   date          not null,
    situacao        varchar(20)   not null,
    observacoes     varchar(2000),
    criado_em       timestamp     not null,
    atualizado_em   timestamp     not null,
    constraint ck_atendimento_situacao check (situacao in ('ABERTO', 'EM_ANDAMENTO', 'CONCLUIDO', 'CANCELADO'))
);

create index ix_atendimento_cliente on atendimento (cliente_id);
create index ix_atendimento_tipo_servico on atendimento (tipo_servico_id);
create index ix_atendimento_responsavel on atendimento (responsavel_id);
