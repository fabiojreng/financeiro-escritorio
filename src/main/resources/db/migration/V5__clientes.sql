-- Permite pesquisar nomes sem depender de acentos (ex.: "joao" encontra "João").
create extension if not exists unaccent;

create table cliente (
    id            bigint generated by default as identity primary key,
    nome          varchar(150)  not null,
    cpf           varchar(11),
    telefone      varchar(30),
    observacoes   varchar(2000),
    data_cadastro date          not null,
    ativo         boolean       not null default true,
    criado_em     timestamp     not null,
    atualizado_em timestamp     not null,
    constraint ck_cliente_cpf check (cpf is null or cpf ~ '^[0-9]{11}$')
);

create unique index uk_cliente_cpf on cliente (cpf) where cpf is not null;
create index ix_cliente_nome on cliente (lower(nome));
