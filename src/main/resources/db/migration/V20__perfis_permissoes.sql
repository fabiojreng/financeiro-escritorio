alter table usuario add column perfil_id bigint references perfil (id);

update usuario u
set perfil_id = (select p.id from perfil p
                 where p.nome = case u.perfil when 'ADMIN' then 'Administrador' else 'Operador' end);

alter table usuario
    alter column perfil_id set not null,
    drop constraint ck_usuario_perfil,
    drop column perfil;

create index ix_usuario_perfil on usuario (perfil_id);
