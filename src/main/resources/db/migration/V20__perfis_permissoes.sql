create table perfil (
    id            bigint generated by default as identity primary key,
    nome          varchar(60)  not null,
    descricao     varchar(255),
    sistema       boolean      not null default false,
    ativo         boolean      not null default true,
    criado_em     timestamp    not null,
    atualizado_em timestamp    not null
);

create unique index uk_perfil_nome on perfil (lower(nome));

create table perfil_permissao (
    perfil_id bigint      not null references perfil (id),
    permissao varchar(50) not null,
    primary key (perfil_id, permissao)
);

insert into perfil (nome, descricao, sistema, ativo, criado_em, atualizado_em)
values ('Administrador', 'Acesso completo ao sistema, inclusive usuários, perfis e histórico de operações.',
        true, true, now(), now()),
       ('Operador', 'Rotina do escritório: cadastros, agenda de pagamentos, honorários e despesas.',
        false, true, now(), now());

insert into perfil_permissao (perfil_id, permissao)
select p.id, x.permissao
from perfil p
cross join (values ('CLIENTES_VISUALIZAR'), ('CLIENTES_EDITAR'), ('CLIENTES_INATIVAR'),
                   ('CADASTROS_RESPONSAVEIS'), ('CADASTROS_TIPOS_SERVICO'),
                   ('AGENDA_VISUALIZAR'), ('AGENDA_EDITAR'), ('AGENDA_ALTERAR_STATUS'), ('AGENDA_EXPORTAR'),
                   ('HONORARIOS_VISUALIZAR'), ('HONORARIOS_EDITAR'),
                   ('REPASSES_VISUALIZAR'), ('REPASSES_EDITAR'),
                   ('DESPESAS_VISUALIZAR'), ('DESPESAS_EDITAR'), ('DESPESAS_CANCELAR'), ('DESPESAS_CADASTROS'),
                   ('DESPESAS_ENVIAR_FECHAMENTO'), ('DESPESAS_REABRIR_FECHAMENTO'),
                   ('RELATORIOS_VISUALIZAR'),
                   ('ADMIN_USUARIOS'), ('ADMIN_PERFIS'), ('ADMIN_AUDITORIA')) as x (permissao)
where p.nome = 'Administrador';

