create table repasse (
    id                  bigint generated by default as identity primary key,
    atendimento_id      bigint         not null references atendimento (id),
    destinatario_id     bigint         not null references responsavel (id),
    descricao           varchar(500)   not null,
    valor_previsto      numeric(15, 2) not null,
    data_prevista       date           not null,
    valor_pago          numeric(15, 2),
    data_pagamento      date,
    situacao            varchar(20)    not null,
    observacoes         varchar(2000),
    motivo_cancelamento varchar(500),
    cancelado_em        timestamp,
    cancelado_por       varchar(100),
    criado_em           timestamp      not null,
    atualizado_em       timestamp      not null,
    constraint ck_repasse_valor_previsto check (valor_previsto > 0),
    constraint ck_repasse_valor_pago check (valor_pago is null or valor_pago > 0),
    constraint ck_repasse_situacao check (situacao in ('PENDENTE', 'PAGO', 'CANCELADO')),
    constraint ck_repasse_pagamento_completo check ((valor_pago is null) = (data_pagamento is null)),
    constraint ck_repasse_pago check (situacao <> 'PAGO' or valor_pago is not null),
    constraint ck_repasse_pendente check (situacao <> 'PENDENTE' or valor_pago is null),
    constraint ck_repasse_cancelamento
        check (situacao <> 'CANCELADO' or (motivo_cancelamento is not null and cancelado_em is not null))
);

create index ix_repasse_atendimento on repasse (atendimento_id);
create index ix_repasse_destinatario on repasse (destinatario_id);
create index ix_repasse_data_prevista on repasse (data_prevista);
