-- Vida financeira dos funcionários no mês: vales, empréstimos, descontos, extras e o acerto mensal.
-- Não é folha de pagamento: INSS, FGTS, IRRF, férias e 13º continuam com a contabilidade.

create table funcionario (
    id                bigint generated by default as identity primary key,
    nome              varchar(150)   not null,
    cpf               varchar(11),
    cargo             varchar(100),
    data_admissao     date           not null,
    data_desligamento date,
    salario_base      numeric(15, 2) not null,
    dia_pagamento     integer        not null,
    banco             varchar(100),
    agencia           varchar(20),
    conta             varchar(30),
    chave_pix         varchar(150),
    observacoes       varchar(2000),
    ativo             boolean        not null default true,
    criado_em         timestamp      not null,
    atualizado_em     timestamp      not null,
    constraint ck_funcionario_cpf check (cpf is null or cpf ~ '^[0-9]{11}$'),
    constraint ck_funcionario_salario check (salario_base > 0),
    constraint ck_funcionario_dia_pagamento check (dia_pagamento between 1 and 31),
    constraint ck_funcionario_desligamento check (data_desligamento is null or data_desligamento >= data_admissao)
);

create unique index uk_funcionario_cpf on funcionario (cpf) where cpf is not null;
create index ix_funcionario_nome on funcionario (lower(nome));

create table emprestimo_funcionario (
    id                   bigint generated by default as identity primary key,
    funcionario_id       bigint         not null references funcionario (id),
    data_concessao       date           not null,
    valor_total          numeric(15, 2) not null,
    numero_parcelas      integer        not null,
    primeira_competencia date           not null,
    forma_pagamento      varchar(20)    not null,
    observacoes          varchar(2000),
    situacao             varchar(20)    not null,
    quitado_em           timestamp,
    quitado_por          varchar(100),
    motivo_cancelamento  varchar(500),
    cancelado_em         timestamp,
    cancelado_por        varchar(100),
    criado_em            timestamp      not null,
    atualizado_em        timestamp      not null,
    constraint ck_emprestimo_funcionario_valor check (valor_total > 0),
    constraint ck_emprestimo_funcionario_parcelas check (numero_parcelas between 1 and 120),
    constraint ck_emprestimo_funcionario_competencia check (extract(day from primeira_competencia) = 1),
    constraint ck_emprestimo_funcionario_forma
        check (forma_pagamento in ('DINHEIRO', 'PIX', 'TRANSFERENCIA', 'BOLETO', 'OUTRO')),
    constraint ck_emprestimo_funcionario_situacao check (situacao in ('EM_ABERTO', 'QUITADO', 'CANCELADO')),
    constraint ck_emprestimo_funcionario_quitacao
        check (situacao <> 'QUITADO' or quitado_em is not null),
    constraint ck_emprestimo_funcionario_cancelamento
        check (situacao <> 'CANCELADO' or (motivo_cancelamento is not null and cancelado_em is not null))
);

create index ix_emprestimo_funcionario_funcionario on emprestimo_funcionario (funcionario_id);

create table lancamento_funcionario (
    id                  bigint generated by default as identity primary key,
    funcionario_id      bigint         not null references funcionario (id),
    data                date           not null,
    competencia         date           not null,
    tipo                varchar(30)    not null,
    valor               numeric(15, 2) not null,
    forma_pagamento     varchar(20),
    descricao           varchar(200),
    observacoes         varchar(2000),
    emprestimo_id       bigint references emprestimo_funcionario (id),
    numero_parcela      integer,
    situacao            varchar(20)    not null,
    motivo_cancelamento varchar(500),
    cancelado_em        timestamp,
    cancelado_por       varchar(100),
    criado_em           timestamp      not null,
    atualizado_em       timestamp      not null,
    constraint ck_lancamento_funcionario_valor check (valor > 0),
    constraint ck_lancamento_funcionario_competencia check (extract(day from competencia) = 1),
    constraint ck_lancamento_funcionario_tipo
        check (tipo in ('VALE', 'PARCELA_EMPRESTIMO', 'DESCONTO', 'BONIFICACAO', 'HORA_EXTRA', 'REEMBOLSO')),
    constraint ck_lancamento_funcionario_forma
        check (forma_pagamento is null or forma_pagamento in ('DINHEIRO', 'PIX', 'TRANSFERENCIA', 'BOLETO', 'OUTRO')),
    constraint ck_lancamento_funcionario_motivo_desconto check (tipo <> 'DESCONTO' or descricao is not null),
    constraint ck_lancamento_funcionario_emprestimo
        check ((tipo = 'PARCELA_EMPRESTIMO') = (emprestimo_id is not null)),
    constraint ck_lancamento_funcionario_situacao check (situacao in ('ATIVO', 'CANCELADO')),
    constraint ck_lancamento_funcionario_cancelamento
        check (situacao <> 'CANCELADO' or (motivo_cancelamento is not null and cancelado_em is not null))
);

create index ix_lancamento_funcionario_competencia on lancamento_funcionario (funcionario_id, competencia);
create index ix_lancamento_funcionario_data on lancamento_funcionario (data);
create index ix_lancamento_funcionario_emprestimo on lancamento_funcionario (emprestimo_id);

-- Acerto mensal de um funcionário. Enquanto está pago, a competência do funcionário fica fechada;
-- os totais guardam o retrato do acerto no momento do pagamento.
create table fechamento_funcionario (
    id                 bigint generated by default as identity primary key,
    funcionario_id     bigint         not null references funcionario (id),
    competencia        date           not null,
    pago               boolean        not null,
    data_pagamento     date,
    forma_pagamento    varchar(20),
    pago_em            timestamp,
    pago_por           varchar(100),
    salario_base       numeric(15, 2),
    total_bonificacoes numeric(15, 2),
    total_reembolsos   numeric(15, 2),
    total_vales        numeric(15, 2),
    total_parcelas     numeric(15, 2),
    total_descontos    numeric(15, 2),
    liquido            numeric(15, 2),
    reaberto_em        timestamp,
    reaberto_por       varchar(100),
    motivo_reabertura  varchar(500),
    criado_em          timestamp      not null,
    atualizado_em      timestamp      not null,
    constraint uk_fechamento_funcionario unique (funcionario_id, competencia),
    constraint ck_fechamento_funcionario_competencia check (extract(day from competencia) = 1),
    constraint ck_fechamento_funcionario_forma
        check (forma_pagamento is null or forma_pagamento in ('DINHEIRO', 'PIX', 'TRANSFERENCIA', 'BOLETO', 'OUTRO')),
    constraint ck_fechamento_funcionario_pagamento
        check (not pago or (data_pagamento is not null and forma_pagamento is not null and pago_em is not null
                            and pago_por is not null and salario_base is not null and total_bonificacoes is not null
                            and total_reembolsos is not null and total_vales is not null
                            and total_parcelas is not null and total_descontos is not null and liquido is not null)),
    constraint ck_fechamento_funcionario_reabertura
        check ((reaberto_em is null) = (motivo_reabertura is null))
);

-- O Administrador já recebe tudo por ser perfil de sistema; as linhas mantêm o banco igual ao enum.
-- O Operador não recebe nada: salário e descontos são dados sensíveis.
insert into perfil_permissao (perfil_id, permissao)
select p.id, x.permissao
from perfil p
cross join (values ('FUNCIONARIOS_VISUALIZAR'), ('FUNCIONARIOS_EDITAR'), ('FUNCIONARIOS_CANCELAR'),
                   ('FUNCIONARIOS_FECHAR'), ('FUNCIONARIOS_REABRIR'), ('FUNCIONARIOS_RELATORIOS')) as x (permissao)
where p.nome = 'Administrador';
