alter table pagamento_agendado drop constraint ck_pagamento_agendado_situacao_honorario;
alter table pagamento_agendado add constraint ck_pagamento_agendado_situacao_honorario
    check (situacao_honorario in ('A_RECEBER', 'RECEBIDO', 'NEGOCIADO', 'PARCIAL', 'EM_ATRASO'));

create table negociacao_honorario (
    id                     bigint generated by default as identity primary key,
    pagamento_agendado_id  bigint         not null references pagamento_agendado (id),
    valor_original         numeric(15, 2) not null,
    valor_negociado        numeric(15, 2) not null,
    desconto               numeric(15, 2) not null,
    motivo                 varchar(2000)  not null,
    data_negociacao        date           not null,
    registrado_por         varchar(100)   not null,
    situacao               varchar(20)    not null,
    criado_em              timestamp      not null,
    atualizado_em          timestamp      not null,
    constraint ck_negociacao_valor_original check (valor_original > 0),
    constraint ck_negociacao_valor_negociado check (valor_negociado > 0),
    constraint ck_negociacao_desconto check (desconto >= 0 and desconto = valor_original - valor_negociado),
    constraint ck_negociacao_valor_maximo check (valor_negociado <= valor_original),
    constraint ck_negociacao_situacao check (situacao in ('ATIVA', 'SUBSTITUIDA'))
);

create unique index uk_negociacao_ativa on negociacao_honorario (pagamento_agendado_id) where situacao = 'ATIVA';
create index ix_negociacao_pagamento on negociacao_honorario (pagamento_agendado_id);

create table parcela_honorario (
    id                  bigint generated by default as identity primary key,
    negociacao_id       bigint         not null references negociacao_honorario (id),
    numero              integer        not null,
    vencimento          date           not null,
    valor               numeric(15, 2) not null,
    situacao            varchar(20)    not null,
    motivo_cancelamento varchar(500),
    cancelada_em        timestamp,
    cancelada_por       varchar(100),
    criado_em           timestamp      not null,
    atualizado_em       timestamp      not null,
    constraint ck_parcela_valor check (valor > 0),
    constraint ck_parcela_numero check (numero > 0),
    constraint ck_parcela_situacao check (situacao in ('ABERTA', 'PAGA', 'CANCELADA')),
    constraint ck_parcela_cancelamento
        check (situacao <> 'CANCELADA' or (motivo_cancelamento is not null and cancelada_em is not null))
);

create index ix_parcela_negociacao on parcela_honorario (negociacao_id);
create index ix_parcela_vencimento on parcela_honorario (vencimento);

create table recebimento_honorario (
    id                  bigint generated by default as identity primary key,
    parcela_id          bigint         not null references parcela_honorario (id),
    data_recebimento    date           not null,
    valor               numeric(15, 2) not null,
    forma_pagamento     varchar(20)    not null,
    observacoes         varchar(2000),
    cancelado           boolean        not null default false,
    motivo_cancelamento varchar(500),
    cancelado_em        timestamp,
    cancelado_por       varchar(100),
    criado_em           timestamp      not null,
    atualizado_em       timestamp      not null,
    constraint ck_recebimento_valor check (valor > 0),
    constraint ck_recebimento_forma
        check (forma_pagamento in ('DINHEIRO', 'PIX', 'TRANSFERENCIA', 'BOLETO', 'OUTRO')),
    constraint ck_recebimento_cancelamento
        check (not cancelado or (motivo_cancelamento is not null and cancelado_em is not null))
);

create index ix_recebimento_parcela on recebimento_honorario (parcela_id);
create index ix_recebimento_data on recebimento_honorario (data_recebimento);
