create table previsao_beneficio (
    id               bigint generated by default as identity primary key,
    atendimento_id   bigint         not null references atendimento (id),
    data_prevista    date           not null,
    valor_estimado   numeric(15, 2) not null,
    valor_confirmado numeric(15, 2),
    data_efetiva     date,
    tipo_pagamento   varchar(30)    not null,
    situacao         varchar(30)    not null,
    observacoes      varchar(2000),
    criado_em        timestamp      not null,
    atualizado_em    timestamp      not null,
    constraint ck_previsao_tipo_pagamento
        check (tipo_pagamento in ('PRIMEIRO_PAGAMENTO', 'RETROATIVO', 'COMPETENCIA_MENSAL', 'OUTRO')),
    constraint ck_previsao_situacao
        check (situacao in ('PREVISTO', 'AGUARDANDO_CONFIRMACAO', 'LIBERADO', 'ADIADO', 'CANCELADO')),
    constraint ck_previsao_valor_estimado check (valor_estimado >= 0),
    constraint ck_previsao_valor_confirmado check (valor_confirmado is null or valor_confirmado > 0),
    constraint ck_previsao_liberado
        check (situacao <> 'LIBERADO' or (data_efetiva is not null and valor_confirmado is not null))
);

create index ix_previsao_atendimento on previsao_beneficio (atendimento_id);
create index ix_previsao_data_prevista on previsao_beneficio (data_prevista);
