create table pagamento_agendado (
    id               bigint generated by default as identity primary key,
    cliente_id       bigint         not null references cliente (id),
    responsavel_id   bigint         not null references responsavel (id),
    tipo_servico_id  bigint         not null references tipo_servico (id),
    data_recebimento date           not null,
    valor            numeric(15, 2) not null,
    banco            varchar(80)    not null,
    status           varchar(20)    not null,
    observacoes      varchar(2000),
    criado_em        timestamp      not null,
    atualizado_em    timestamp      not null,
    constraint ck_pagamento_agendado_status check (status in ('AGENDADO', 'PAGO', 'PENDENTE')),
    constraint ck_pagamento_agendado_valor check (valor > 0)
);

create index ix_pagamento_agendado_data on pagamento_agendado (data_recebimento);
create index ix_pagamento_agendado_cliente on pagamento_agendado (cliente_id);
