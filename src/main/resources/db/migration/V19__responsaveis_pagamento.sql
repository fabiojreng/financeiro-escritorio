create table pagamento_responsavel (
    id                    bigint generated by default as identity primary key,
    pagamento_agendado_id bigint         not null references pagamento_agendado (id),
    responsavel_id        bigint         not null references responsavel (id),
    valor_repasse         numeric(15, 2),
    situacao_repasse      varchar(20)    not null default 'PENDENTE',
    criado_em             timestamp      not null,
    atualizado_em         timestamp      not null,
    constraint uk_pagamento_responsavel unique (pagamento_agendado_id, responsavel_id),
    constraint ck_pagamento_responsavel_valor_repasse check (valor_repasse is null or valor_repasse > 0),
    constraint ck_pagamento_responsavel_situacao_repasse check (situacao_repasse in ('PENDENTE', 'PAGO'))
);

create index ix_pagamento_responsavel_pagamento on pagamento_responsavel (pagamento_agendado_id);
create index ix_pagamento_responsavel_responsavel on pagamento_responsavel (responsavel_id);

insert into pagamento_responsavel (pagamento_agendado_id, responsavel_id, valor_repasse, situacao_repasse,
                                   criado_em, atualizado_em)
select id, responsavel_id, valor_repasse, situacao_repasse, criado_em, atualizado_em
from pagamento_agendado;

alter table pagamento_agendado
    drop constraint ck_pagamento_agendado_valor_repasse,
    drop constraint ck_pagamento_agendado_situacao_repasse,
    drop column responsavel_id,
    drop column valor_repasse,
    drop column situacao_repasse;
