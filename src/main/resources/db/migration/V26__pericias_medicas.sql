-- Agenda de perícias médicas dos clientes, que antes era anotada no caderno do escritório.

alter table cliente add column nome_mae varchar(150);

create table tipo_pericia (
    id            bigint generated by default as identity primary key,
    nome          varchar(100) not null,
    descricao     varchar(500),
    ativo         boolean      not null default true,
    criado_em     timestamp    not null,
    atualizado_em timestamp    not null
);

create unique index uk_tipo_pericia_nome on tipo_pericia (lower(nome));

-- Tipos usados no caderno; podem ser editados ou desativados pela tela.
insert into tipo_pericia (nome, ativo, criado_em, atualizado_em) values
    ('Perícia Médica Inicial', true, now(), now()),
    ('Avaliação Médica Pericial', true, now(), now()),
    ('Avaliação Médica Pericial BPC', true, now(), now());

create table local_pericia (
    id            bigint generated by default as identity primary key,
    nome          varchar(100) not null,
    endereco      varchar(300),
    ativo         boolean      not null default true,
    criado_em     timestamp    not null,
    atualizado_em timestamp    not null
);

create unique index uk_local_pericia_nome on local_pericia (lower(nome));

-- Data, horário e local podem ficar em branco: a perícia é anotada antes de o INSS marcar a data.
create table pericia (
    id                    bigint generated by default as identity primary key,
    cliente_id            bigint       not null references cliente (id),
    tipo_pericia_id       bigint       not null references tipo_pericia (id),
    responsavel_id        bigint       not null references responsavel (id),
    local_pericia_id      bigint references local_pericia (id),
    data                  date,
    horario               time,
    observacoes           varchar(2000),
    situacao              varchar(20)  not null,
    motivo_situacao       varchar(500),
    situacao_alterada_em  timestamp,
    situacao_alterada_por varchar(100),
    remarcada_para_id     bigint references pericia (id),
    criado_em             timestamp    not null,
    atualizado_em         timestamp    not null,
    constraint ck_pericia_horario check (horario is null or data is not null),
    constraint ck_pericia_situacao
        check (situacao in ('AGENDADA', 'REALIZADA', 'FALTOU', 'REMARCADA', 'CANCELADA')),
    constraint ck_pericia_remarcacao check ((situacao = 'REMARCADA') = (remarcada_para_id is not null)),
    constraint ck_pericia_cancelamento check (situacao <> 'CANCELADA' or motivo_situacao is not null),
    constraint ck_pericia_realizada check (situacao <> 'REALIZADA' or data is not null)
);

create index ix_pericia_data on pericia (data, horario);
create index ix_pericia_situacao on pericia (situacao);
create index ix_pericia_cliente on pericia (cliente_id);

-- Perícia é rotina do escritório: Administrador e Operador recebem o módulo inteiro.
insert into perfil_permissao (perfil_id, permissao)
select p.id, x.permissao
from perfil p
cross join (values ('PERICIAS_VISUALIZAR'), ('PERICIAS_EDITAR'), ('PERICIAS_ALTERAR_SITUACAO'),
                   ('CADASTROS_TIPOS_PERICIA'), ('CADASTROS_LOCAIS_PERICIA')) as x (permissao)
where p.nome in ('Administrador', 'Operador');
